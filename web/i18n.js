let current = "en";
export const language = () => current;
export function setLanguage(value) {
  current = value === "pl" ? "pl" : "en";
}
export function t(message, values = {}) {
  const text = current === "pl" ? polish[message] ?? message : message;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? (typeof values[name] === "number" ? new Intl.NumberFormat(current).format(values[name]) : String(values[name])) : match);
}

// Capture authored text nodes once, before application rendering. Translate
// nodes/attributes in place: labels keep their inputs and user text is untouched.
export function initLanguage(document) {
  let saved;
  try { saved = localStorage.getItem("timetable.language"); } catch { /* Storage may be disabled. */ }
  setLanguage(["pl", "en"].includes(saved) ? saved : navigator.language.toLowerCase().startsWith("pl") ? "pl" : "en");
  const texts = [], attributes = [];
  const walker = document.createTreeWalker(document.documentElement, 4);
  for (let node; (node = walker.nextNode());) {
    const key = node.data.trim();
    if (Object.hasOwn(polish, key) && !node.parentElement?.closest("script, style, code")) texts.push([node, key, node.data.match(/^\s*/)[0], node.data.match(/\s*$/)[0]]);
  }
  for (const node of document.querySelectorAll("*")) for (const name of ["title", "aria-label", "placeholder", "content"]) {
    const key = node.getAttribute(name);
    if (Object.hasOwn(polish, key)) attributes.push([node, name, key]);
  }
  function apply() {
    document.documentElement.lang = current;
    for (const [node, key, before, after] of texts) if (node.isConnected) node.data = before + t(key) + after;
    for (const [node, name, key] of attributes) if (node.isConnected) node.setAttribute(name, t(key));
    for (const button of document.querySelectorAll("[data-language]")) button.setAttribute("aria-pressed", String(button.dataset.language === current));
  }
  for (const button of document.querySelectorAll("[data-language]")) button.addEventListener("click", () => {
    if (button.dataset.language === current) return;
    setLanguage(button.dataset.language);
    try { localStorage.setItem("timetable.language", current); } catch { /* The switch still works without storage. */ }
    apply();
    document.dispatchEvent(new Event("languagechange"));
  });
  apply();
}
